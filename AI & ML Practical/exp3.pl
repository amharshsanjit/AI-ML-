% ==========================================
% EXPERIMENT 3
% List Operations
% ==========================================


% ------------------------------------------
% APPEND TWO LISTS
% ------------------------------------------

my_append([], L, L).

my_append([H|T], L, [H|R]) :-
    my_append(T, L, R).


% ------------------------------------------
% REVERSE A LIST
% ------------------------------------------

my_reverse([], []).

my_reverse([H|T], R) :-
    my_reverse(T, RT),
    my_append(RT, [H], R).


% ------------------------------------------
% MEMBER SEARCH
% ------------------------------------------

my_member(X, [X|_]).

my_member(X, [_|T]) :-
    my_member(X, T).


% ------------------------------------------
% LIST LENGTH
% ------------------------------------------

my_length([], 0).

my_length([_|T], N) :-
    my_length(T, N1),
    N is N1 + 1.